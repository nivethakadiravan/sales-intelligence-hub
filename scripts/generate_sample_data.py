"""Generate sql/03_sample_data.sql with realistic demo data.

Run:  python scripts/generate_sample_data.py

Output is deterministic (fixed random seed). Sales are inserted with
received_amount = 0; payments are inserted afterwards so the triggers fill
in received_amount, pending_amount and status - no manual calculation.
"""

from __future__ import annotations

import random
import sys
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.auth import hash_password  # noqa: E402

rng = random.Random(2026)

BRANCHES = [
    ("Chennai", "Arun Kumar"),
    ("Bangalore", "Priya Sharma"),
    ("Hyderabad", "Ravi Teja"),
    ("Delhi", "Neha Gupta"),
    ("Mumbai", "Rahul Desai"),
    ("Pune", "Sneha Patil"),
]

# Course price list (INR). gross_sales = price minus a small discount.
PRODUCTS = {"DS": 60000, "DA": 45000, "BA": 40000, "FSD": 55000}

FIRST = ["Aarav", "Vivaan", "Aditya", "Vihaan", "Arjun", "Sai", "Karthik", "Rohan",
         "Ishaan", "Harish", "Diya", "Ananya", "Kavya", "Meera", "Lakshmi", "Divya",
         "Pooja", "Swathi", "Nisha", "Revathi", "Gokul", "Manoj", "Deepak", "Sanjay",
         "Keerthana", "Bhavya", "Yamini", "Fathima", "Joseph", "Imran"]
LAST = ["R", "S", "K", "M", "Iyer", "Nair", "Reddy", "Singh", "Patel", "Menon",
        "Rao", "Khan", "Das", "Pillai", "Verma", "Joshi"]

METHODS = ["UPI", "Cash", "Card"]
METHOD_WEIGHTS = [0.55, 0.2, 0.25]

N_SALES = 150
START = date(2026, 1, 1)
END = date(2026, 10, 31)


def sql_str(v: str) -> str:
    return "'" + v.replace("'", "''") + "'"


def main() -> None:
    lines: list[str] = [
        "-- =====================================================================",
        "-- Sales Intelligence Hub - Sample Data (generated by",
        "-- scripts/generate_sample_data.py - do not edit by hand)",
        "-- Payments are inserted AFTER sales so triggers compute",
        "-- received_amount, pending_amount and status automatically.",
        "-- =====================================================================",
        "",
        "USE sales_management_system;",
        "",
        "-- Branches",
        "INSERT INTO branches (branch_name, branch_admin_name) VALUES",
    ]
    lines.append(",\n".join(f"  ({sql_str(b)}, {sql_str(a)})" for b, a in BRANCHES) + ";")

    # ---- users: 1 Super Admin + 1 Admin per branch -------------------------
    lines += ["", "-- Users (passwords are salted PBKDF2-SHA256 hashes; see README for demo logins)",
              "INSERT INTO users (username, password, branch_id, role, email) VALUES"]
    user_rows = [("superadmin", "Super@123", "NULL", "Super Admin", "superadmin@salesHub.in")]
    for i, (branch, _) in enumerate(BRANCHES, start=1):
        key = branch.lower()
        user_rows.append((f"{key}_admin", f"{branch}@123", str(i), "Admin", f"{key}.admin@salesHub.in"))
    vals = []
    for username, pwd, bid, role, email in user_rows:
        salt = f"{rng.getrandbits(128):032x}"
        vals.append(f"  ({sql_str(username)}, {sql_str(hash_password(pwd, salt=salt))}, "
                    f"{bid}, {sql_str(role)}, {sql_str(email.lower())})")
    lines.append(",\n".join(vals) + ";")

    # ---- sales --------------------------------------------------------------
    sales = []
    used_mobiles: set[str] = set()
    span = (END - START).days
    for _ in range(N_SALES):
        # mild upward trend: later months are a bit busier
        offset = int(span * (rng.random() ** 0.8))
        sale_date = START + timedelta(days=offset)
        branch_id = rng.choices(range(1, len(BRANCHES) + 1), weights=[24, 20, 16, 14, 16, 10])[0]
        product = rng.choices(list(PRODUCTS), weights=[35, 25, 15, 25])[0]
        discount = rng.choice([0, 0, 2000, 3000, 5000, 7500])
        gross = PRODUCTS[product] - discount
        while True:
            mobile = str(rng.choice([6, 7, 8, 9])) + "".join(str(rng.randint(0, 9)) for _ in range(9))
            if mobile not in used_mobiles:
                used_mobiles.add(mobile)
                break
        name = f"{rng.choice(FIRST)} {rng.choice(LAST)}"
        sales.append((branch_id, sale_date, name, mobile, product, gross))

    sales.sort(key=lambda s: s[1])
    lines += ["", "-- Customer sales (received_amount starts at 0; triggers maintain it)",
              "INSERT INTO customer_sales (branch_id, date, name, mobile_number, product_name, gross_sales) VALUES"]
    lines.append(",\n".join(
        f"  ({b}, '{d.isoformat()}', {sql_str(n)}, '{m}', '{p}', {g:.2f})" for b, d, n, m, p, g in sales
    ) + ";")

    # ---- payment splits -----------------------------------------------------
    payments = []
    for sale_id, (_, sale_date, _, _, _, gross) in enumerate(sales, start=1):
        r = rng.random()
        if r < 0.08:
            continue  # no payment yet
        fully_paid = r < 0.62
        n_parts = rng.choices([1, 2, 3, 4], weights=[30, 35, 25, 10])[0]
        target = gross if fully_paid else round(gross * rng.uniform(0.25, 0.85), -2)
        # split target into n_parts rounded chunks
        cuts = sorted(rng.uniform(0.15, 0.85) for _ in range(n_parts - 1))
        parts, prev = [], 0.0
        for c in cuts:
            amt = round(target * (c - prev), -2)
            parts.append(amt)
            prev = c
        parts.append(round(target - sum(parts), 2))
        pay_date = sale_date
        for amt in parts:
            if amt <= 0:
                continue
            pay_date = min(pay_date + timedelta(days=rng.randint(0, 25)), date(2026, 11, 5))
            method = rng.choices(METHODS, weights=METHOD_WEIGHTS)[0]
            payments.append((sale_id, pay_date, amt, method))

    lines += ["", "-- Payment splits (each INSERT fires trg_payment_after_insert)",
              "INSERT INTO payment_splits (sale_id, payment_date, amount_paid, payment_method) VALUES"]
    lines.append(",\n".join(
        f"  ({s}, '{d.isoformat()}', {a:.2f}, '{m}')" for s, d, a, m in payments
    ) + ";")
    lines.append("")

    out = ROOT / "sql" / "03_sample_data.sql"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out.relative_to(ROOT)}: {len(BRANCHES)} branches, {len(user_rows)} users, "
          f"{len(sales)} sales, {len(payments)} payments")


if __name__ == "__main__":
    main()
